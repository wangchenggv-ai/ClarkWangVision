// 新增型号时在这里加一行，key 与飞书订单「产品型号」字段保持一致
const ENTRIES_BY_SKU = {
  "Ultra双效": _Ultra,
  // "D8": _D8,
  // "时空之眼A": _TKA,
};

// ── 索引构建 ──────────────────────────────────────────────────────────────────
const _sphCylIdx = new Map(); // key: "sku\0sph/cyl" → entry
const _serialIdx  = new Map(); // key: "sku\0serial"  → entry

for (const [sku, entries] of Object.entries(ENTRIES_BY_SKU)) {
  for (const e of entries) {
    _serialIdx.set(`${sku}\0${e.s}`, e);
    if (e.sph !== null && e.cyl !== null) {
      _sphCylIdx.set(`${sku}\0${e.sph.toFixed(2)}/${e.cyl.toFixed(2)}`, e);
    }
  }
}

export function lookupBySerial(sku, serialNo) {
  const key = String(serialNo).padStart(3, "0");
  return _serialIdx.get(`${sku}\0${key}`) ?? null;
}

export function lookupBySphCyl(sku, sph, cyl) {
  const s = Number(sph);
  const c = Number(cyl);
  if (isNaN(s) || isNaN(c)) return null;
  return _sphCylIdx.get(`${sku}\0${s.toFixed(2)}/${c.toFixed(2)}`) ?? null;
}

export function getAllEntries(sku) {
  if (sku) return ENTRIES_BY_SKU[sku] ?? [];
  return ENTRIES_BY_SKU;
}

export function getSupportedSkus() {
  return Object.keys(ENTRIES_BY_SKU);
}
